export const landingBySlug = (slug) => LANDINGS.find((l) => l.slug === slug) || null;

export const landingPath = (landing) => `/rabota/${landing.slug}`;

// Страница профессии для категории вакансии — для ссылки «Все вакансии» под
// карточкой.
export const landingForCategory = (category) =>
  LANDINGS.find((l) => l.group === 'profession' && l.params.category === category) || null;

// Ссылка «Смотреть все» — тот же фильтр на странице списка. У «сегодня» своего
// фильтра на странице заказов нет: там и так свежие сверху.
export function listPath(landing) {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(landing.params)) {
    if (key !== 'fresh') query.set(key, String(value));
  }
  const qs = query.toString();
  return `/${landing.kind}${qs ? `?${qs}` : ''}`;
}
