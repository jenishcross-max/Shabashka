// Какие фильтры понимает страница списка (Vacancies.jsx, AllOrders.jsx).
const LIST_FILTERS = {
  vacancies: ['category', 'city', 'q', 'employmentType', 'students'],
  orders: ['category', 'city', 'q', 'students', 'workFormat', 'fresh'],
};

// Ссылка «Смотреть все» — тот же фильтр на странице списка. У «сегодня» своего
// фильтра на странице заказов нет: там и так свежие сверху. Фильтра, которого
// список не знает («без опыта», «онлайн» у вакансий), — null: ссылка показала бы
// всё подряд, такая страница листает сама.
export function listPath(landing, kind = landing.kind) {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(landing.params)) {
    if (!LIST_FILTERS[kind].includes(key)) return null;
    if (key !== 'fresh') query.set(key, String(value));
  }
  const qs = query.toString();
  return `/${kind}${qs ? `?${qs}` : ''}`;
}
