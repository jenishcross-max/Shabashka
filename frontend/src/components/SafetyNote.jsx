// Две вещи, которые должны стоять рядом с телефоном в любом объявлении.
//
// Первая — предупреждение про предоплату. Почти все истории «меня обманули на
// Шабашке» начинаются с перевода вперёд, и одна строка рядом с кнопкой WhatsApp
// снимает их лучше любого раздела в правилах, куда никто не заходит.
//
// Вторая — пометка об импорте. Бот берёт объявления из открытых чатов и публикует
// их от имени администратора: человек о публикации не просил, и никто его не
// проверял. Выдавать такое за проверенное объявление сервиса нельзя — это ровно
// та подмена, из-за которой площадка перестаёт быть посредником.
export default function SafetyNote({ isImported, className = '' }) {
  return (
    <div className={`safety-note ${className}`.trim()}>
      {!!isImported && (
        <p className="safety-note-imported">
          ℹ️ Объявление взято из открытых чатов. Автора мы не проверяли, и он не подавал его
          на сайт сам — данные могли устареть.
        </p>
      )}
      <p className="safety-note-money">
        ⚠️ Не переводите деньги вперёд — ни «за материалы», ни «за бронь», ни «за оформление».
        Шабашка не участвует в расчётах и не сможет вернуть перевод.
      </p>
    </div>
  );
}
