// Сколько просмотров показать посетителю. Счётчик считает только открытия
// карточки, и у объявления там обычно 0–1: человек видит «никто не смотрел» и
// уходит с сайта. Поэтому посетителю к настоящему числу прибавляется добавка от
// 10 до 100 — так решил владелец сайта (октябрь 2026).
//
// Добавка у каждого объявления своя и постоянная: считается от id, а не
// случайно, — иначе число прыгало бы при каждом обновлении страницы. Соседние id
// перемешиваем (fmix32 из MurmurHash3), чтобы у объявлений подряд не шли
// числа с одним шагом.
//
// Автор объявления видит настоящее число: по нему он судит, работает ли
// объявление. Настоящее же — в «Мои вакансии», «Мои заказы», «Мои
// объявления» и в админке.
function mix(id) {
  let h = id | 0;
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

export function shownViews(item, isOwner = false) {
  const real = Number(item.views) || 0;
  return isOwner ? real : real + 10 + (mix(Number(item.id) || 0) % 91);
}
