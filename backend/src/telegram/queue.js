// Очередь разбора. Пачку скриншотов админ кидает разом, Telegram присылает их
// отдельными сообщениями почти одновременно — а бесплатный Groq за минуту
// пропускает примерно полтора разбора на один ключ. Без очереди половина пачки
// вернулась бы ошибкой лимита; здесь же скриншоты просто ждут своей очереди, а
// паузу между ними держит сам разбор (см. waitForCapacity в extract.js).
//
// Если ключей несколько (GROQ_API_KEY через запятую) или подключён запасной
// шлюз (FALLBACK_API_URL), у каждой такой дорожки свой независимый лимит —
// значит, можно разбирать несколько скриншотов одновременно, по одному на
// дорожку. Отсюда и CONCURRENCY: с одним ключом Groq очередь работает как
// раньше, по одной задаче за раз.
//
// Очередь в памяти процесса: перезапуск бэкенда её теряет. Хранить её в базе
// было бы честнее, но file_id скриншота живёт у Telegram не вечно, и «доразбор
// через сутки после падения» всё равно не сработал бы — проще переслать пачку
// заново.
//
// Очередь двухуровневая. Скриншот админа — это человек, который стоит над
// телефоном и ждёт ответа; посты из чужих групп (см. sourceWatcher.js) идут
// потоком и подождут. Без разделения один разговорчивый чат-барахолка забивал
// бы очередь на полчаса вперёд, и присланный руками скриншот разбирался бы
// последним. Поэтому фоновые задачи всегда встают в хвост, а обычные — перед
// первой фоновой.
const extract = require('./extract');

const CONCURRENCY = Math.max(1, extract.KEY_COUNT);

// Сколько задача имеет право занимать дорожку. Срок нужен не для скорости:
// дорожек у очереди ровно столько, сколько ключей, и задача, которая не
// заканчивается и не падает, забирает одну из них навсегда. С одним ключом это
// значит, что бот молча перестаёт разбирать что бы то ни было: объявления
// уходят в очередь и не возвращаются оттуда никогда, а в чате — тишина.
// Обычный разбор укладывается в минуту-другую (см. CALL_TIMEOUT_MS и
// waitForCapacity в extract.js), так что десять минут — это уже поломка.
// Дорожку в этот момент отпускаем: задача, возможно, ещё жива, и мешать ей мы
// не можем, но останавливать из-за неё всё остальное — хуже.
const JOB_TIMEOUT_MS = 10 * 60 * 1000;

const jobs = [];
let active = 0;

// Сколько задач сейчас висят сверх срока. Нужно только для отчёта в /stats:
// по этому числу видно, что дело не в лимитах, а в зависшем запросе.
let stuck = 0;

function pump() {
  while (active < CONCURRENCY && jobs.length) {
    const { run } = jobs.shift();
    active += 1;
    // Дорожку освобождает либо сама задача, либо сторож — но ровно один раз.
    let freed = false;
    const free = (bySentry) => {
      if (freed) return;
      freed = true;
      active -= 1;
      if (bySentry) {
        stuck += 1;
        console.error(
          `[очередь] задача не закончилась за ${Math.round(JOB_TIMEOUT_MS / 60000)} мин — освобождаю дорожку, чтобы не встало всё остальное`
        );
      } else {
        clearTimeout(sentry);
      }
      pump();
    };
    const sentry = setTimeout(() => free(true), JOB_TIMEOUT_MS);
    sentry.unref(); // сторож не должен сам по себе держать процесс живым
    run()
      // Свои ошибки задача ловит сама, и до сюда дойти им нечем. Но если
      // однажды дойдут, это не должно кончиться падением всего бэкенда: Node с
      // пятнадцатой версии убивает процесс за необработанный промис, и сайт
      // ушёл бы в перезапуск из-за одного неразобранного объявления.
      .catch((err) => console.error('[очередь] задача упала необработанной ошибкой:', err))
      .finally(() => {
        // Задача, которую сторож уже списал, всё-таки закончилась — счётчик
        // зависших возвращаем на место, дорожку второй раз не отпускаем.
        if (freed) stuck = Math.max(0, stuck - 1);
        free(false);
      });
  }
}

// Возвращает номер партии: 1 — разбор начнётся прямо сейчас (или как только
// освободится один из ключей), 2 — только после того как первая партия
// разберётся, и так далее.
function add(run, { background = false, priority = false } = {}) {
  // Место в очереди: реклама — в голову, фоновая задача — в хвост, обычная —
  // перед первой фоновой. Реклама обгоняет и обычные скриншоты: за неё платят,
  // и ждать, пока разберётся присланная перед ней пачка, она не должна.
  let index = jobs.length;
  if (priority) {
    index = 0;
  } else if (!background) {
    const firstBackground = jobs.findIndex((job) => job.background);
    if (firstBackground !== -1) index = firstBackground;
  }
  jobs.splice(index, 0, { run, background });

  const position = Math.ceil((index + 1 + active) / CONCURRENCY);
  pump();
  return position;
}

// Сколько задач ждёт разбора (без тех, что уже разбираются). Автоимпорт пишет
// это число в лог: по нему сразу видно, насколько бот отстаёт от групп.
const size = () => jobs.length;

// Сколько задач зависло сверх срока (см. JOB_TIMEOUT_MS). Показываем в /stats:
// молчащий бот и бот, упёршийся в лимиты, снаружи выглядят одинаково, а
// лечатся по-разному.
const stalled = () => stuck;

module.exports = { add, size, stalled, JOB_TIMEOUT_MS };
