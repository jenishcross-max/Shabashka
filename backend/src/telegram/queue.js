// Очередь разбора. Пачку скриншотов админ кидает разом, Telegram присылает их
// отдельными сообщениями почти одновременно — а бесплатный Groq за минуту
// пропускает примерно полтора разбора. Без очереди половина пачки вернулась бы
// ошибкой лимита; здесь же скриншоты просто ждут своей очереди, а паузу между
// ними держит сам разбор (см. waitForCapacity в extract.js).
//
// Очередь в памяти процесса: перезапуск бэкенда её теряет. Хранить её в базе
// было бы честнее, но file_id скриншота живёт у Telegram не вечно, и «доразбор
// через сутки после падения» всё равно не сработал бы — проще переслать пачку
// заново.
const jobs = [];
let running = false;

async function run() {
  running = true;
  try {
    while (jobs.length) {
      const job = jobs.shift();
      await job(); // свои ошибки задача ловит сама — иначе очередь встала бы на первой
    }
  } finally {
    running = false;
  }
}

// Возвращает место в очереди: 1 — разбор начнётся прямо сейчас.
function add(job) {
  jobs.push(job);
  const position = jobs.length + (running ? 1 : 0);
  if (!running) run();
  return position;
}

module.exports = { add };
