// Работа за границей. Её «Шабашка» не публикует нигде: ни из чатов, ни за
// деньги по /ad, ни с формы на сайте. Площадка — про работу в Кыргызстане.
//
// Дело не в формальности. Отправлять людей на работу за рубеж в Кыргызстане
// вправе только агентства с разрешением Минтруда, а закон «О внешней трудовой
// миграции» (ст. 29) за рекламу такого набора спрашивает и со СМИ. К тому же
// «работа в Корее, билет оплатим» — обычный ход вербовщиков. Проверить
// агентство мы не можем, поэтому не публикуем вовсе.
//
// То же правило есть в промпте (см. buildSystem в extract.js), но одной модели
// здесь мало: срочная реклама, ролики и картинки идут мимо неё, а сама она
// иногда пропускает. Проверка по словам не зависит ни от модели, ни от лимитов.

// Куда чаще всего зовут на заработки. Основа названия с русскими окончаниями;
// кыргызская форма — то же название плюс -да/-га («Москвада», «Кореяга»), её
// добавляет SUFFIX. Прилагательные («турецкая одежда», «корейская кухня») не
// совпадают: после основы у них идёт буква, а не конец слова.
const PLACES = [
  'за\\s+(?:рубеж|границ)\\p{L}*',
  'зарубеж\\p{L}*',
  'чет\\s+(?:өлкө|эл)\\p{L}*',
  'росси[яиюе]',
  '(?<!\\.)рф', // но не домен «.рф»
  'москв[аеуы]',
  'подмосковь[еяю]',
  '(?:санкт-)?петербург[аеу]?',
  'питер[аеу]?',
  'спб',
  'екатеринбург[аеу]?',
  'новосибирск[аеу]?',
  'сургут[аеу]?',
  'якутск[аеу]?',
  'казахстан[аеу]?',
  'казакстан',
  'алматы',
  'алма-ат[аеуы]',
  'астан[аеуы]',
  'коре[яиюе]',
  'сеул[аеу]?',
  'турци[яиюе]',
  'т[уү]ркия',
  'стамбул[аеу]?',
  'оаэ',
  'эмират(?:ы|ах|ов)',
  'дуба[йея]',
  'европ[аеуы]',
  'германи[яиюе]',
  'польш[аеуи]',
  'чехи[яиюе]',
  '(?:велико)?британи[яиюе]',
  'англи[яиюе]',
  'лондон[аеу]?',
  'сша',
  'америк[аеуи]',
  'япони[яиюе]',
  'израил[ьея]',
  'кита[йея]',
  'кытай',
];
const SUFFIX = '(?:да|та|до|то|де|те|дө|тө|га|ка|го|ко|ге|ке|гө|кө)?';
const PLACE_WORD = `(?:${PLACES.join('|')})${SUFFIX}(?!\\p{L})`;
const PLACE = new RegExp(`(?<!\\p{L})${PLACE_WORD}`, 'iu');

// Слова про работу. Нужны там, где одно название страны ничего не решает: в
// записке на доске и в рекламе «туры в Турцию» — это продажа, а не работа.
const JOB =
  /(?<!\p{L})(?:работ(?:а|е|у|ы|ать)(?!\p{L})|ваканси|требу(?:ется|ются|емся)|рабоч(?:ие|их|им)(?!\p{L})|сотрудник|работник|вахт|трудоустр|зарплат|оклад|набор(?!\p{L})|приглашаем|жумуш|кызматкер|айлык)/iu;

// Что местом работы не является. Вырезаем до поиска, иначе без объявления
// остались бы продавец турецкой одежды и повар из кафе «Сеул» в Бишкеке.
const NOT_THERE = [
  // заведение с «заграничным» названием: кафе «Сеул», кофейня Стамбул, посольство США
  /(?<!\p{L})(?:кафе|ресторан[аеу]?|кофейн[яиюе]|магазин[аеу]?|бутик[аеу]?|салон[аеу]?|бар[аеу]?|клуб[аеу]?|трц|тц|отел[ьяюе]|гостиниц[аеуы]|чайхан[аеуы]|компани[яиюе]|фирм[аеуы]|посольств[оау])\s+(?:[«"“][^»"”\n]{1,40}[»"”]|[\p{L}-]+)/giu,
  // валюта, а не место: «от 500 долларов США»
  /(?<!\p{L})долл\p{L}*\.?\s*сша(?!\p{L})/giu,
  // откуда, а не куда: «одежда из Турции и Китая», «вещи из-за границы»,
  // «на границе с Казахстаном». Перечень тянем, только пока в нём идут места:
  // в «с проживанием, Питер» после запятой начинается уже другое.
  new RegExp(
    `(?<!\\p{L})(?:из-за|из|со|от|с)\\s+(?:${PLACE_WORD}(?:(?:\\s*,\\s*|\\s+и\\s+)${PLACE_WORD})*|[\\p{L}-]+)`,
    'giu'
  ),
];

// Возвращает слово, на котором сработала проверка («Корее», «за рубежом»), или
// пустую строку. job — заказ или вакансия: им хватает одного названия места,
// работать там, где назвали.
function abroadWork(text, { job = false } = {}) {
  const clean = NOT_THERE.reduce((acc, re) => acc.replace(re, ' '), String(text ?? ''));
  const place = PLACE.exec(clean);
  if (!place) return '';
  return job || JOB.test(clean) ? place[0] : '';
}

module.exports = { abroadWork };
