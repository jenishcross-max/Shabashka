// Категории по профессиям. Список категорий писался под услуги (уборка, ремонт,
// сантехника), и в октябре 2026 87% вакансий из чатов лежали в «Другом»:
// официанта нельзя было найти фильтром, а под «работа официантом Бишкек» не
// было страницы (см. docs/research/2026-10-18-marketing-research.md).
//
// Модель теперь видит эти категории в списке, а здесь — запасной разбор по
// словам: им же раскладываются старые объявления из «Другого» (backfill) и
// новые, которые модель всё равно туда положила (см. applyDefaults в
// telegram/imports.js). Слова — из настоящих заголовков чатов, по-русски и
// по-кыргызски.
const db = require('./db');
const categoriesRepo = require('./categoriesRepo');
const { invalidate } = require('./cache');

const FALLBACK = 'Другое';

const CATEGORIES = require('./professionCategories');

// [категория, кто (профессия), где (место)]. Профессия надёжнее места: «грузчик
// в магазин» — грузчик, а не продажи. Порядок важен: «официант, кассир,
// администратор» — общепит, «кассир жана газ куюучу» — заправка.
// \b здесь не годится — для кириллицы он не работает, — поэтому основы слов.
const RULES = [
  [
    'Общепит',
    /официант|офицант|повар|ашпоз|пекар|наабайчы|бармен|бариста|сушист|сушеф|шаурм|фаст ?фуд|фас ?фуд|посудомо|посудамо|пасудамо|идиш жуу|кухработ|заг[ао]товщ|раннер|басбой|кондитер|шашлычн|пиццайол/iu,
    /кафе|ресторан|чайхан|столов|бургер|лаваш|самса|караоке|суши|пицц/iu,
  ],
  ['Автомойка, СТО и АЗС', /автомой|вулканиз|шиномонтаж|автомеханик|автоэлектрик|рихтовщ|газ куюучу|заправщ|автосервис/iu, /мойк|азс|заправк/iu],
  ['Швейный цех', /швея|швеи|швеял|швей(?![а-яё])|тиг[үуе]|закройщ|утюжн|үтүкчү|утукчу|нитк/iu, /швейн/iu],
  ['Охрана', /охран|сторож|күзөтчү|кузотчу|вахт[её]р/iu, null],
  ['Уборка', /техничк|уборщ|клининг|горничн|тазалоо|тазалагыч/iu, null],
  ['Красота', /парикмах|маникюр|педикюр|бровист|косметолог|массаж|барбер|лешмейк|визажист|наращиван/iu, /салон красот/iu],
  ['Склад и грузчики', /грузчик|жүк ташуу|жук ташуу|погрузк|разгрузк|кладовщ|упаковщ|упактовщ|комплектовщ|фасовщ|сборщ/iu, /склад/iu],
  ['Водители и курьеры', /водител|курьер|доставщик|экспедитор|айдоочу|таксист|дальнобой/iu, /доставк|такси/iu],
  [
    'Стройка и разнорабочие',
    /разнораб|разно раб|разнароб|разнараб|разна раб|р\/рабоч|подсобник|каменщ|кладчик|сварщ|маляр|штукатур|плиточн|бетонщ|арматурщ|монтажник|кровельщ|строител/iu,
    /стройк|кирпич|бетон|газоблок|газо-?бетон|брусчатк|забор|фасад|траншея|опалубк|профнастил|болгарк|балгарк|отбойник|сетка ур|сетка мак|грунт|вентиляц|монтаж(?!ер|ёр)|на объект|бригад/iu,
  ],
  [
    'Продажи',
    /продав|сатуучу|касс|торгов(ый|ого|ые|ых|ая)|агент|мерчендайз|консультант|промоутер|менеджер по продаж/iu,
    /магазин|бутик|гастроном/iu,
  ],
  ['Офис', /администратор|оператор|колл-центр|call|бухгалтер|секретар|менеджер/iu, /офис/iu],
];

const byWho = (text) => (RULES.find(([, who]) => who.test(text)) || [])[0] || null;
const byWhere = (text) => (RULES.find(([, , where]) => where && where.test(text)) || [])[0] || null;

// Профессия по заголовку и описанию; не узнали — null. Сначала «кто» в
// заголовке, потом «кто» в описании, и только потом «где»: «В магазин нужны
// парни» с «грузчики на склад» в описании — склад, а не продажи.
function guess(title, description = '') {
  const head = String(title || '');
  const body = String(description || '');
  return byWho(head) || byWho(body) || byWhere(head) || byWhere(body);
}

// Открытые вакансии и заказы из «Другого» — по профессиям. Только в те
// категории, что есть в списке: админ мог какую-то удалить. Повторный проход
// ничего не трогает: из «Другого» уходит только узнанное.
async function backfill() {
  const known = new Set(await categoriesRepo.listNames());
  const moved = { vacancies: 0, orders: 0 };
  for (const table of Object.keys(moved)) {
    const { rows } = await db.query(
      `SELECT id, title, description FROM ${table} WHERE status = 'open' AND category = $1`,
      [FALLBACK]
    );
    const ids = new Map();
    for (const row of rows) {
      const category = guess(row.title, row.description);
      if (category && known.has(category)) ids.set(category, [...(ids.get(category) || []), row.id]);
    }
    for (const [category, list] of ids) {
      const result = await db.query(
        `UPDATE ${table} SET category = $1 WHERE category = $2 AND id = ANY($3::int[])`,
        [category, FALLBACK, list]
      );
      moved[table] += result.rowCount || 0;
    }
  }
  if (moved.vacancies || moved.orders) {
    invalidate('home:');
    console.log(`[профессии] из «Другого» разложил: вакансий ${moved.vacancies}, заказов ${moved.orders}`);
  }
  return moved;
}

module.exports = { CATEGORIES, FALLBACK, guess, backfill };
