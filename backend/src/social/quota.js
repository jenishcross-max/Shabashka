// Instagram считает публикации по аккаунту-получателю, а не по приложению: N
// постов за скользящие сутки, причём в счёт идут и неудачные попытки создать
// контейнер. Само N зашивать нельзя — Meta его поднимала уже дважды (25 в 2021,
// потом 50, сейчас 100), и молодым аккаунтам режет ниже документированного.
// Настоящее число отдаёт content_publishing_limit (см. publishingLimit в
// instagram.js), а эта цифра — только на случай, когда спросить не вышло.
const FALLBACK_TOTAL = 100;

// Сколько мест в сутках держим в запасе. Ролики идут под потолком «всего минус
// запас», а запасной ход с картинкой забирает уже из самого запаса: он нужен
// ровно тогда, когда обычного места не осталось, и без этого зазора объявление
// не выходило бы вовсе. Остаток заодно страхует публикации руками из приложения.
const RESERVE = 10;

const WINDOW_MS = 24 * 60 * 60 * 1000;

// Насколько долго считаем ответ Meta свежим. Минута — не экономия вызовов (их у
// одного ролика три десятка), а защита от лишнего похода на каждый чих: за
// минуту число публикаций меняем разве что мы сами, а своё мы и так считаем.
const REMOTE_TTL_MS = 60 * 1000;

// Свои попытки за сутки — { at, seq }. Счётчик живёт в памяти процесса и после
// перезапуска занижен — на бесплатном Render сервис засыпает, — поэтому он не
// основной, а запасной: основным служит ответ Meta. Нужен он и когда ответ
// есть: между синхронизациями свои публикации надо на что-то класть.
//
// У попытки, кроме времени, есть порядковый номер, и делит их «до/после
// синхронизации» именно он. По времени не выходит: sync и take нередко
// случаются в одну миллисекунду, и попытка, поданная сразу после ответа Meta,
// тогда терялась — место считалось свободным, хотя уже занято.
const attempts = [];
let seq = 0;

// Последний ответ Meta: { used, total, at, seq }.
let remote = null;

function sweep(now) {
  while (attempts.length && now - attempts[0].at >= WINDOW_MS) attempts.shift();
}

function fresh() {
  return remote && Date.now() - remote.at < REMOTE_TTL_MS ? remote : null;
}

// Настоящий потолок площадки — тот, выше которого Meta ответит подкодом 2207042
// и спишет попытку впустую.
function hardLimit() {
  const r = fresh();
  return r && r.total ? r.total : FALLBACK_TOTAL;
}

// Мягкий потолок: под ним идут ролики. Дальше объявление уезжает картинкой и
// добирает остаток до настоящего.
function dailyLimit() {
  return Math.max(1, hardLimit() - RESERVE);
}

function used() {
  const now = Date.now();
  sweep(now);
  const r = fresh();
  // Meta посчитала всё, что было до синхронизации, — своё добавляем только за
  // время после неё, иначе одна и та же публикация учлась бы дважды.
  if (r) return r.used + attempts.filter((a) => a.seq > r.seq).length;
  return attempts.length;
}

function left() {
  return Math.max(0, dailyLimit() - used());
}

// Спрашивает у площадки настоящие числа. fetchLimit передаётся снаружи, чтобы
// счётчик не знал ни про Instagram, ни про его токен: считать он умеет, ходить
// в сеть — не его дело. Ошибку глотаем намеренно — не ответила площадка, идём
// по своему счётчику: он занижен, но это лучше, чем не публиковать вовсе.
async function sync(fetchLimit) {
  if (fresh()) return remote;
  try {
    const { used: remoteUsed, total } = await fetchLimit();
    remote = { used: remoteUsed, total, at: Date.now(), seq };
    console.log(`[квота] Instagram: ${remoteUsed} из ${total} за сутки`);
  } catch (err) {
    console.log(`[квота] настоящую норму не узнать (${err.message}) — считаю по своему счётчику`);
  }
  return remote;
}

// Отмечаем попытку, а не успех: Instagram списывает единицу квоты за каждый
// созданный контейнер, даже если публикация потом не прошла. Возвращает false,
// если места в сутках уже нет — тогда к Meta лучше не ходить вовсе.
// limit — под каким потолком считать: ролик идёт под мягким, картинка запасного
// хода может дотянуться до настоящего.
function take(limit = dailyLimit()) {
  const now = Date.now();
  sweep(now);
  if (used() >= limit) return false;
  seq += 1;
  attempts.push({ at: now, seq });
  return true;
}

// Когда освободится место, если сейчас его нет: самая старая попытка выпадает
// из окна ровно через сутки после себя. Время знаем только по своим попыткам —
// Meta отдаёт число, но не отметки времени, — поэтому пока своих нет, обещать
// нечем.
function freeAt() {
  sweep(Date.now());
  if (used() < dailyLimit() || !attempts.length) return null;
  return new Date(attempts[0].at + WINDOW_MS);
}

module.exports = { take, used, left, freeAt, sync, hardLimit, dailyLimit, RESERVE };
