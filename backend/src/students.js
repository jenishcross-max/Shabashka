// Подходит ли работа студентам — по тексту самого объявления.
//
// Решаем только по прямым словам автора: «можно студентам», «для студентов»,
// «совмещать с учёбой», «студенттерге». Догадки вроде «вечерняя смена — значит,
// студенту подойдёт» сюда не берём: пометка «🎓 Для студентов» на сайте и в
// ролике — это обещание, и давать его должен работодатель, а не мы.
//
// Модель для этого не нужна: слов немного, и проверка по ним точнее и бесплатна.
// Сетевой найм тоже любит «гибкий график для студентов», но его отсеивает
// spam.js раньше, чем объявление дойдёт до этой пометки.

const flat = (text) =>
  String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ');

// Прямо сказано, что студентов ждут.
const YES = new RegExp(
  [
    // «студент», «студентам», «студентов», «студентки», «студенты» — но не
    // «студия»: корень другой.
    'студент',
    'студенттер',
    'совмеща\\S*\\s+с\\s+уч[её]б',
    'с\\s+учеб\\S*\\s+совмеща',
    'окуу\\s+менен\\s+(айкалыштыр|катар)',
    'после\\s+пар(?![\\p{L}])',
  ].join('|'),
  'u'
);

// Прямо сказано обратное. Отказы пишут как угодно: «Не студенты.»,
// «Возраст от 20 лет, не студентка», «Студенты – не беспокоить!»,
// «🚫 Студенттер кабыл алынбайт», «Студенттерди албайбыз». Перечислять фразы
// бесполезно — список пополнялся бы после каждой жалобы. Поэтому смотрим на
// кусок текста вокруг самого слова: есть в нём отрицание — это отказ.
//
// Кусок — до запятой, точки, скобки или значка-пункта: «опыт не нужен, можно
// студентам» — это «можно», а «не» относится к опыту. 🚫 и ❌ сами начинают
// кусок и делают его отказом.
const CROSS = '🚫❌⛔✖🙅';
const CLAUSES = new RegExp(`(?=[${CROSS}])|[.!?;,()\\[\\]\\n]|(?![${CROSS}])\\p{Extended_Pictographic}`, 'u');

const NEGATION = new RegExp(
  [
    `[${CROSS}]`,
    // «не», «нет», «нельзя» — где угодно в куске; «не только студентам» —
    // наоборот, приглашение (см. clause ниже).
    '(?<![\\p{L}])(?:не|нет|нельзя|запрещ\\p{L}*)(?![\\p{L}])',
    // «без студентов», «кроме студентов» — только прямо перед словом: «студентам
    // можно без опыта» — не отказ.
    '(?<![\\p{L}])(?:без|кроме)\\s+студент',
    // Кыргызское отрицание: «эмес», «жок» и глагол с -бай-/-бас-/-бош-:
    // «алынбайт», «албайбыз», «жарабайт», «болбойт», «болбосун».
    '(?<![\\p{L}])(?:эмес|жок)(?![\\p{L}])',
    '\\p{L}+[бп][аеоө](?:йт|йбыз|йбиз|йбуз|йбүз|сун|сүн|сын|син|шу|шү|шы|ши|с)(?![\\p{L}])',
  ].join('|'),
  'u'
);

// Кусок, в котором кроме самих студентов ничего нет: «Студенты, школьники —
// не беспокоить», «Студенты? Нет», «(студентки)». Что про них сказано — в
// следующем куске.
const BARE = /^(?:студент\p{L}*|школьник\p{L}*|учащ\p{L}*|и|или|[—–-])?$/u;
const isBare = (clause) => clause.split(' ').every((word) => BARE.test(word));

// Куски с упоминанием студентов (или учёбы) — вместе с тем, что про них
// сказано, если сам кусок голый.
function mentions(text) {
  const clauses = String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(CLAUSES)
    .map((c) => (c || '').replace(/\s+/g, ' ').trim())
    .filter(Boolean);
  const found = [];
  clauses.forEach((clause, i) => {
    if (!YES.test(clause)) return;
    let said = clause;
    for (let j = i + 1; isBare(said.replace(/[^\p{L}\s—–-]/gu, '').trim()) && j < clauses.length; j++) {
      said += ` ${clauses[j]}`;
    }
    found.push(said.replace(/(?<![\p{L}])не\s+только(?![\p{L}])/gu, ''));
  });
  return found;
}

// Про студентов сказано «нет» — хоть в одном месте. Тогда пометки не будет,
// даже если рядом «гибкий график для студентов»: обещание на сайте не должно
// спорить с самим объявлением.
function refused(text) {
  return mentions(text).some((said) => NEGATION.test(said));
}

// Студенты здесь не работники, а клиенты: «репетитор для студентов»,
// «общежитие для студентов», «скидка студентам». Такое объявление про услугу
// или жильё, и пометка «работа для студентов» на нём была бы враньём.
const CLIENTS =
  /(репетитор|курс\S*|обучени\S*\s+для|общежити|квартир\S*|комнат\S*|жиль\S*|скидк\S*|подготовк\S*)[^.\n]{0,40}студент|студент\S*[^.\n]{0,20}скидк/u;

function forStudents(text) {
  const said = mentions(text);
  if (!said.length) return false;
  if (said.some((s) => NEGATION.test(s))) return false;
  if (CLIENTS.test(flat(text))) return false;
  return true;
}

// Как назвать объявление в подписи поста, в канале и в карточке у админа:
// студенческое — сразу словами «для студентов», чтобы это было видно первой
// строкой, ещё до описания. У доски пометки нет: там продажа и аренда.
function label(listingType, parsed = {}) {
  const students = Boolean(parsed && parsed.for_students) && listingType !== 'board';
  if (listingType === 'vacancy') return students ? '🎓 Вакансия для студентов' : '💼 Вакансия';
  if (listingType === 'board') return '📌 Объявление';
  return students ? '🎓 Подработка для студентов' : '🧰 Заказ';
}

module.exports = { forStudents, refused, label };
