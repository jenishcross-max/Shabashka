// Отсев того, что модель пропускает: сетевой маркетинг и оформление чужих
// документов за деньги.
//
// Правила про то и другое есть и в промпте разбора (см. extract.js), но модели
// там не одна, а лесенка. Когда суточная норма основной выбрана, разбор уходит
// на запасные, и те правила держат хуже: в начале октября 2026 на сайт и в
// соцсети снова поехали «Помощник администратора в офис, от 16 до 40 лет,
// всему научим» и «доверенность у нотариуса на машину из Китая, деньги сразу».
// Поэтому здесь проверка без модели — по словам. Она же экономит норму: пост
// из группы, пойманный здесь, к модели уже не идёт.
//
// Ошибиться тут дороже, чем в модели: отказ по словам не перепроверяет никто.
// Поэтому ни одно слово само по себе ничего не решает — нужна сумма признаков,
// и у каждого правила свой порог. Перед правкой гоняйте test/spam.test.js: там
// и мусор, который должен отсеиваться, и настоящие вакансии, которые должны
// проходить.

// Сравниваем в нижнем регистре и с «е» вместо «ё»: «партнёр» и «партнер»
// пишут одинаково часто.
const flat = (text) =>
  String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ');

// Первое совпадение — его показываем в причине отказа: по нему сразу видно,
// если правило ошиблось.
function first(text, re) {
  const m = re.exec(text);
  return m ? m[0].trim() : '';
}

// Сумма признаков. strong — сработал хоть один весомый (вес 2 и больше): без
// него слабые не решают ничего, сколько бы их ни набралось. «Машина из Китая,
// по доверенности, деньги сразу» — три слабых и обычная продажа; «международная
// компания ищет водителей в нашу команду, доход от 15000 в неделю» — три слабых
// и обычная вакансия.
function tally(text, signs) {
  let score = 0;
  let strong = false;
  const hits = [];
  for (const [re, weight] of signs) {
    const hit = first(text, re);
    if (!hit) continue;
    score += weight;
    if (weight >= 2) strong = true;
    hits.push(hit);
  }
  return { score, strong, hits };
}

// ── Сетевой маркетинг ───────────────────────────────────────────────────────

// Прямые слова. Вес — насколько слово само по себе выдаёт сеть.
const MLM_WORDS = [
  [/сетев\S*\s+(бизнес|маркетинг|компани)|(?<![\p{L}])(млм|mlm)(?![\p{L}])|network\s+marketing|тармактык\s+(бизнес|маркетинг)/u, 3],
  [/финансов\S*\s+(свобод|независим)|финансылык\s+эркиндик/u, 2],
  [/пассивн\S*\s+доход/u, 2],
  [/ищ(у|ем)\s+(партнер|единомышленник|лидер)|бизнес[- ]партнер|бизнес-?партнер/u, 2],
  [/доход\s+без\s+вложени|без\s+вложени\S*\s+доход|без\s+вложений/u, 1],
  [/международн\S*\s+компани/u, 1],
  [/в\s+(нашу\s+|свою\s+)?команду/u, 1],
  [/доход\s+(от\s+)?\d[\d\s]*\s*(сом|\$|долл\S*)?\s*(в|за)\s+(неделю|день|сутки)/u, 1],
  [/работа\s+(через|в|по)\s+(телефон|интернет)|онлайн[- ]работа|работа\s+онлайн\s+через\s+телефон/u, 1],
];

// Марки сетевых компаний. Сама марка — ещё не сеть: «продаю крем Орифлейм,
// 500с» — обычная продажа. Сеть — когда рядом с маркой зовут в работу и доход.
const MLM_BRANDS =
  /атоми|atomy|орифлейм|oriflame|эйвон|(?<![\p{L}])avon(?![\p{L}])|гринвей|greenway|фаберлик|faberlic|амвей|amway|гербалайф|herbalife|nl\s+international|сибирск\S*\s+здоров|siberian\s+wellness|coral\s+club|корал\s+клаб|mary\s+kay|мэри\s+кэй|тяньши|tiens|vertera|вертера|armelle|армель/u;
const MLM_RECRUIT =
  /доход|заработ|партнер|команд|бизнес|сотрудничеств|кызматташ|ищем|ищу|набор|приглаша|работ|жумуш/u;

// «Работа в офисе» без профессии — самый частый вид сетевого найма. По форме
// это образцовая вакансия, и модель её охотно пропускает: «Помощник
// администратора в офис! Можно без опыта — всему научим. Карьерный рост. От 16
// до 40 лет, знание кыргызского». Должность при этом названа, но такая, за
// которой нет никакой работы.
const VAGUE_ROLE = new RegExp(
  [
    '(помощни|ассистент)\\S*\\s+(администратор|руководител|менеджер|директор)\\S*',
    '(администратор|менеджер|сотрудник|специалист|оператор)\\S*\\s+(в|на)\\s+офис\\S*',
    'в\\s+офис\\S*\\s+(требу|нуж|ищ|набира|пригла)',
    'менеджер\\S*\\s+по\\s+(персонал|подбор)',
    'hr[- ]?менеджер',
    'кеңсеге|офиске\\s+(кызматкер|жумушчу|адам|кыз|бал)',
  ].join('|'),
  'u'
);

// Признаки такого найма. Каждый по отдельности бывает и у настоящей вакансии —
// решает их сумма.
const OFFICE_SIGNS = [
  /в\s+офис|офиске|кеңсе/u,
  /в\s+центре\s+(города|бишкека|оша)|шаардын\s+борбор/u,
  /карьерн\S*\s+рост|карьералык\s+өсүү/u,
  /всему\s+научим|научим|обучени\S*\s+(бесплатн|с\s+нуля)|өзүбүз\s+үйрөт|үйрөтөбүз/u,
  /без\s+опыта|опыт\s+(работы\s+)?не\s+(важен|обязателен|нужен|требуется)|можно\s+и\s+без|тажрыйба\s+(талап\s+кылынбайт|шарт\s+эмес|кереги\s+жок|милдеттүү\s+эмес)/u,
  /(от|с)\s*1[4-9]\s*(до|-|–)\s*[2-6]\d|1[4-9]\s*[-–]\s*[2-6]\d\s*(лет|жаш)|1[4-9]\s*жаштан\s*[2-6]\d/u,
  /девушк\S*\s+и\s+парн|парн\S*\s+и\s+девушк|кыздар\s*(жана|,|\/|и)\s*балдар|балдар\s*(жана|,|\/|и)\s*кыздар|мужчин\S*\s+и\s+женщин|женщин\S*\s+и\s+мужчин/u,
  /знани\S*\s+(кыргызск|государствен)|кыргыз\s+тилин|кыргызча\s+билүү/u,
  /ответственн|пунктуальн|уверенн\S*\s+в\s+себе|целеустремл|коммуникабельн|стрессоустойчив|жоопкерчил/u,
  /мест\S*\s+ограничен|орун\s+(аз|чектелүү)/u,
  /гибк\S*\s+график|удобн\S*\s+график|для\s+студентов|студенттер/u,
  /с\s+паспортом|паспорту?\s+менен/u,
  /высок\S*\s+доход|стабильн\S*\s+доход|доход\s+от\s+\d/u,
  /в\s+связи\s+с\s+расширени|кеңейүүгө\s+байланыштуу/u,
  /мам\S*\s+в\s+декрет|декреттеги/u,
];

// Настоящая профессия. Если она названа, «офисное» правило молчит: «в кафе
// требуются официанты, без опыта, научим, от 18 до 30 лет» — обычная вакансия.
const PROFESSION =
  /повар|продав|кассир|водител|официант|бармен|бариста|сварщ|электрик|сантехник|грузчик|уборщ|техничк|швея|швеи|курьер|охран|няня|сиделк|маникюр|парикмахер|бухгалтер|программист|дизайнер|учител|тренер|мойщ|кухн|пекар|кондитер|строител|разнорабоч|штукатур|плиточ|маляр|механик|экспедитор|кладовщ|фармацевт|провизор|врач|медсестр|массаж|косметолог|мастер|упаковщ|комплектовщ|оператор\s+(станк|пк|колл|call)|колл-?центр|call-?центр|таксист|доставщ|секретар|юрист|логист|маркетолог|smm|таргетолог|переводчик|репетитор|воспитател|аниматор|фотограф|видеограф|монтажер|сборщик|грузчик|дворник|садовник|ашпоз|сатуучу|айдоочу|тигүүчү/u;

const HIRING = /требу|ищем|нуж(ен|на|ны)|керек|набор|приглаша|вакансия/u;

function mlm(text) {
  const words = tally(text, MLM_WORDS);
  const brand = first(text, MLM_BRANDS);
  if (brand && MLM_RECRUIT.test(text)) {
    words.score += 3;
    words.strong = true;
    words.hits.push(brand);
  }
  if (words.strong && words.score >= 3) return { kind: 'mlm', reason: 'сетевой маркетинг', hits: words.hits };

  if (PROFESSION.test(text)) return null;
  const signs = OFFICE_SIGNS.filter((re) => re.test(text)).length;
  const role = first(text, VAGUE_ROLE);
  // Должность-пустышка плюс три признака — или вовсе без должности, но с
  // пятью: «требуются девушки и парни, от 17 до 28, без опыта, карьерный
  // рост, места ограничены».
  if ((role && signs >= 3) || (!role && signs >= 5 && HIRING.test(text))) {
    return {
      kind: 'mlm',
      reason: role ? `«${role}» без настоящей работы — похоже на сетевой маркетинг` : 'набор без профессии — похоже на сетевой маркетинг',
      hits: role ? [role] : [],
    };
  }
  return null;
}

// ── Оформление на чужие документы ───────────────────────────────────────────

// Схема с подставными лицами: человеку платят за то, что на его паспорт
// оформят машину из Китая (доверенность у нотариуса), карту, ИП, сим-карту или
// кредит. Отвечать по этим машинам, долгам и штрафам потом ему же. Для
// площадки это то же самое, что продажа документов, — запрещено и за деньги.
const DROP_SIGNS = [
  // Требования «чистоты»: не в браке, без ИП и ОСОО, без кредитов и штрафов.
  // У настоящей работы таких требований не бывает — самый верный признак.
  [/(?<![\p{L}])(загс|брак\S*|ип|осоо|прописк\S*|кредит\S*|штраф\S*|судим\S*)[^.\n!]{0,50}(жарабайт|не\s+подход|не\s+подойд|не\s+берем|болбошу\s+керек)/u, 2],
  [/(на\s+(свой|ваш|твой|свое|себя)\s+(паспорт|имя))|оформить\s+на\s+себя|өз\s+атыңызга|паспортуңузга|атыңызга\s+(каттоо|тариздөө)/u, 2],
  [/(открыть|открыт\S*|оформить|ачып\s+бер)\S*\s+(карт|счет|ип|осоо|сим)|(?<![\p{L}])(ип|осоо|карт\S*|счет\S*)\s+ачып\s+бер|карт\S*\s+ачып|сим-?карт\S*\s+на\s+(ваш|свой)\s+паспорт|продать\s+(карту|аккаунт|паспорт)/u, 2],
  [/довер\S*ност|ишеним\s+кат/u, 1],
  [/нотариус/u, 1],
  [/машин\S*\s+(из|с)\s+китая|китайдан\s+келген|авто\S*\s+(из|с)\s+китая/u, 1],
  [/(эч\s+кандай\s+)?зыяны?\s+(жок|тийбейт)|никакого\s+вреда|без\s+(риска|последствий)|ничего\s+не\s+теряете|ответственност\S*\s+нет/u, 1],
  [/акча(сы)?\s+(дароо|ошол\s+замат)|колго\s+берилет|деньги\s+сразу|сразу\s+на\s+руки|оплата\s+сразу|наличными\s+сразу/u, 1],
];

function drop(text) {
  // «Продаю авто из Китая по доверенности, деньги сразу» — три слабых признака
  // и обычная продажа. Нужна хотя бы одна настоящая примета схемы: требования
  // «чистоты», «на ваш паспорт», открыть карту или ИП.
  const { score, strong, hits } = tally(text, DROP_SIGNS);
  return strong && score >= 3
    ? { kind: 'drop', reason: 'оформление машин или документов на чужое имя за деньги', hits }
    : null;
}

// Что это за мусор, или null. ad — платная реклама: сетевой маркетинг за
// деньги админ выкладывать вправе (см. AD_SUFFIX в extract.js), а оформление
// на чужие документы запрещено и за деньги.
function check(text, { ad = false } = {}) {
  const t = flat(text);
  if (t.length < 15) return null;
  return drop(t) || (ad ? null : mlm(t));
}

// Причина для отчёта: что сработало и на каких словах.
function describe(found) {
  if (!found) return '';
  const words = found.hits.slice(0, 2).map((w) => `«${w}»`).join(', ');
  return found.kind === 'mlm' && found.reason.startsWith('«')
    ? found.reason
    : `${found.reason}${words ? ` (${words})` : ''}`;
}

const LABELS = { mlm: 'сетевой маркетинг', drop: 'оформление на чужие документы' };

module.exports = { check, describe, LABELS };
