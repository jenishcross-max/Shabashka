const PRICE = Number(process.env.AD_PRICE || 50);
const GOAL = Number(process.env.AD_VIEWS_GOAL || 1000);
const SITE = 'шабашка.com';

// Номер и имя получателя в МБанке. Их вписывает владелец в Render: номер счёта
// бот за него не придумает, а без номера он честно скажет, что реквизиты
// пришлёт администратор (см. noMbank).
function mbank() {
  return {
    number: String(process.env.MBANK_NUMBER || '').trim(),
    name: String(process.env.MBANK_NAME || '').trim(),
  };
}

// «1 842», а не «1842» — так числа читаются и в директе.
const num = (n) => Number(n || 0).toLocaleString('ru-RU');

function viewsRu(n) {
  const mod100 = n % 100;
  const mod10 = n % 10;
  if (mod100 >= 11 && mod100 <= 14) return 'просмотров';
  if (mod10 === 1) return 'просмотр';
  if (mod10 >= 2 && mod10 <= 4) return 'просмотра';
  return 'просмотров';
}

function payTo() {
  const { number, name } = mbank();
  return name ? `${number} (${name})` : number;
}

