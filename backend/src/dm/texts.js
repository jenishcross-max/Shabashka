function render(key, lang = 'ru', vars = {}) {
  const set = TEXTS[lang] || TEXTS.ru;
  const fn = set[key] || TEXTS.ru[key];
  if (!fn) throw new Error(`нет текста «${key}»`);
  return fn(vars);
}

