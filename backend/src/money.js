// «4200000» → «4 200 000». Заказы обычно на пару тысяч, и разделитель там не
// нужен, но на доске продают дома и машины — семь цифр подряд человек читает
// пересчётом. Один формат на кадр ролика, подписи к постам и сообщения бота.
function money(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

module.exports = { money };
