// «Поднять» объявление — вернуть его в начало ленты, не создавая новое.
//
// Смысл у кнопки есть, только пока её нельзя нажимать подряд: сортировка «новые»
// идёт по bumped_at, и без промежутка один человек навсегда занимал бы верх
// списка, нажимая её каждые полминуты, — а остальные объявления не увидел бы
// никто. Промежуток задумывался с самого начала (колонка bumped_at появилась
// именно под него), но ни на сайте, ни в API его не было: жать можно было
// сколько угодно.
//
// Считаем от последнего поднятия, а если его не было — от публикации: только что
// поданное объявление и так наверху, поднимать его нечего.
//
// Админку это не касается: там поднимают чужие объявления руками и по делу
// (см. routes/admin.js).
const HOURS = 24;

const MS = HOURS * 60 * 60 * 1000;

// «26 сентября в 14:05» по Бишкеку: сервер живёт по UTC, и без часового пояса
// срок уезжал бы на шесть часов назад — в ответе стояло бы время, которое для
// автора уже прошло.
function when(date) {
  return date.toLocaleString('ru-RU', {
    timeZone: 'Asia/Bishkek',
    day: 'numeric',
    month: 'long',
    hour: '2-digit',
    minute: '2-digit',
  });
}

// Возвращает null, если поднимать уже можно, иначе — готовый ответ с причиной.
// row — строка объявления (нужны bumped_at и created_at).
function tooSoon(row, now = Date.now()) {
  const last = row.bumped_at || row.created_at;
  if (!last) return null;
  const nextAt = new Date(new Date(last).getTime() + MS);
  if (nextAt.getTime() <= now) return null;
  return {
    error: `Поднимать объявление можно раз в сутки. Следующий раз — ${when(nextAt)}.`,
    nextBumpAt: nextAt.toISOString(),
  };
}

module.exports = { tooSoon, HOURS };
