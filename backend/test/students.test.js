// Пометка «🎓 Для студентов» (см. src/students.js): только когда автор прямо
// сказал, что студентов ждут. Это обещание на сайте и в ролике — давать его по
// догадке нельзя.
const test = require('node:test');
const assert = require('node:assert/strict');

const { forStudents, refused } = require('../src/students');

test('прямо сказано, что можно студентам', () => {
  const yes = [
    'Требуются официанты, можно студентам, график гибкий, 0700123456',
    'Вакансия для студентов: промоутер, 4 часа в день',
    'Ищем курьеров. Подойдёт студентам, можно совмещать с учёбой',
    'Кафеге официант керек, студенттер да болот',
    'Студенттерге ылайыктуу жумуш, кечки смена',
    'Работа после пар, оплата каждый день',
    'Бариста в кофейню, студенты приветствуются',
    'Можно совмещать с учебой, смены по 4 часа',
  ];
  for (const text of yes) assert.equal(forStudents(text), true, text);
});

test('о студентах ни слова, или прямо сказано «не берём»', () => {
  const no = [
    'Требуется повар в кафе, график 5/2, з/п 30000',
    'Студентов не берём, только с опытом от 3 лет',
    'Не для студентов: полный день, официальное оформление',
    'Студенттер жарабайт, тажрыйбасы бар адам керек',
    'Студия маникюра ищет мастера',
  ];
  for (const text of no) assert.equal(forStudents(text), false, text);
});

// Отказы из вакансий, которые бот 6 октября пометил «для студентов» (с сайта,
// раздел «Для студентов»: 22 из 28 были такими).
test('отказ как его пишут в группах — не пометка', () => {
  const no = [
    'Требуется девушка на раздачу в столовую. Не студенты. Возраст от 18 до 30 лет. З/П 1600.',
    'Кофейня ищет бариста с опытом работы. Возраст от 20 лет, не студенты. График с 8:30 до 21:00.',
    'Ищем внимательных и коммуникабельных официантов, не студент.',
    'Требуется девушка на раздачу в столовую. Не студентка. Официальное трудоустройство.',
    'Сотрудники в цех полуфабрикатов, 5/2, 08:00–17:00. Студенты – не беспокоить!',
    'С опытом и без опыта, не студенты. График: 5/2, 3/1, 6/1',
    '📌 Тажрыйба талап кылынбайт\n🚫 Студенттер кабыл алынбайт\n🔥 Шашылыш түрдө кызматкерлер керек!',
    'Адрес: Джал 23 18/2. 18-25 чейин / СТУДЕНТТЕР КАБЫЛ АЛЫНБАЙТ❗️',
    'Иш графиги: 6/1. Студенттерди албайбыз. Иш тажрыйбасы талап кылынбайт',
    'Студенты, школьники — не беспокоить',
    'Студенты? Нет.',
    'Берём всех, кроме студентов',
    'Студенттер үчүн эмес, толук күн',
    // Отказ рядом с приглашением — верим отказу: обещание на сайте не должно
    // спорить с текстом.
    'Гибкий график для студентов. Студентов не берём на ночные смены',
  ];
  for (const text of no) {
    assert.equal(forStudents(text), false, text);
    assert.equal(refused(text), true, text);
  }
});

test('«не» о другом рядом с приглашением студентов — не отказ', () => {
  const yes = [
    'Опыт не нужен, можно студентам',
    'Студентам можно без опыта, обучим',
    'Возраст: 17–35 лет. Студентам можно. Есть гибкий график.',
    'Менеджер по продажам. График 5/2 10:00-18:00 (студентам есть гибкий график)',
    'Оператор швейного цеха (студентки)\nСтудентки, принимаем на работу операторами',
    'Швейный цехке грузчик керек! Студент деле болот! График 14:00-20:00',
    'Тажрыйба талап кылынбайт.\nСтуденттер да болот',
    'Не только студентам — берём всех от 18 лет',
    'Работа для студентов на лето. Работа курьером',
  ];
  for (const text of yes) {
    assert.equal(forStudents(text), true, text);
    assert.equal(refused(text), false, text);
  }
});

test('студенты как клиенты, а не работники, — не пометка о работе', () => {
  const no = [
    'Репетитор по математике для студентов и школьников',
    'Сдаю комнату студентам, рядом с КНУ',
    'Скидка студентам 20% на стрижку',
    'Курсы английского для студентов, набор открыт',
  ];
  for (const text of no) assert.equal(forStudents(text), false, text);
});
