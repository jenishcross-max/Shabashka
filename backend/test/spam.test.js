test('платная реклама: сетевой маркетинг пропускаем, оформление на чужие документы — нет', () => {
  assert.equal(spam.check(OFFICE_MLM, { ad: true }), null);
  assert.equal(spam.check('Сетевой бизнес Атоми, ищу партнёров, пассивный доход 0700123456', { ad: true }), null);
  assert.equal(spam.check(CAR_DROP, { ad: true }).kind, 'drop');
});
