// Отсев сетевого маркетинга и «оформления на чужие документы» по словам
// (см. src/spam.js). Модель такое пропускает, когда разбор уходит на запасные
// модели лесенки, а отказ по словам не перепроверяет никто — поэтому здесь и
// мусор, который должен отсеиваться, и настоящие вакансии, которые должны
// проходить.
const test = require('node:test');
const assert = require('node:assert/strict');

const spam = require('../src/spam');

// Ровно те объявления, что в октябре 2026 уехали на сайт и в соцсети.
const OFFICE_MLM = `Ищем Девушек и парней Помощника Администратора в офис! С опытом
Можно и без — всему научим! Что мы предлагаем:
📍 Работа в офисе в центре города
📅 Удобный график: 5/2, с 10:00 до 18:00 для студентов есть гибкий график
📈 Реальный карьерный рост
Требования к кандидату:
🎯 Возраст: от 16 до 40 лет с паспортом
🗣️ Обязательное знание кыргызского языка
🤝 Ответственность, пунктуальность и уверенность в себе
0700 123 456`;

const CAR_DROP = `Нотариуска барып Китайдан келген машинага доверность жазыш керек. Июлга чейин жаздыргандар болот. Балдар/Кыздар. Загс барлар жарабайт. Ип, ОСОО барлар жарабайт. Прописка жоктор жарабайт. Сотко өтүп кеткен штрафы барлар, просроченный кредит барлар жарабайт. 18жаштан өйдө. Эч кандай зыяны тийбейт. Акчасы дароо колго берилет
0555 123 456`;

test('ловит «помощника администратора в офис» и доверенность на машину', () => {
  const office = spam.check(OFFICE_MLM);
  assert.equal(office && office.kind, 'mlm');
  assert.match(spam.describe(office), /помощник\S* администратора/i);

  const car = spam.check(CAR_DROP);
  assert.equal(car && car.kind, 'drop');
  assert.match(spam.describe(car), /на чужое имя/);
});

