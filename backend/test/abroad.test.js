// Работу за границей «Шабашка» не публикует нигде (см. src/abroad.js).
// Проверка по словам стоит рядом с моделью, а не вместо неё: срочная реклама,
// ролики и картинки идут мимо модели, и другого места для проверки у них нет.
const test = require('node:test');
const assert = require('node:assert/strict');

const { abroadWork } = require('../src/abroad');

test('ловит работу за границей, когда названы и место, и работа', () => {
  const cases = [
    ['Работа в Корее! Зарплата 2000$, билет оплачиваем. Тел 0700123456', 'корее'],
    ['Требуются рабочие на стройку в Москву, вахта 60/30', 'москву'],
    ['Кореяга жумушка адам керек, айлык 1500$', 'кореяга'],
    ['Работа за рубежом без предоплаты', 'за рубежом'],
    ['Работа зарубежом, звоните', 'зарубежом'],
    ['Чет өлкөдө жумуш, виза бар', 'чет өлкөдө'],
    ['Вакансии в Польше и Германии для строителей', 'польше'],
    ['Требуется сварщик. Город: Сургут. Зарплата 150000 руб', 'сургут'],
    ['Трудоустройство в ОАЭ, Дубай', 'оаэ'],
    ['Требуется повар в ресторан в Стамбуле', 'стамбуле'],
    ['Набор рабочих из Оша и Нарына в Корею', 'корею'],
    ['Москвада иш бар, жумушчулар керек', 'москвада'],
    ['Работа с проживанием, Питер, зарплата 90 тыс', 'питер'],
    ['Требуются работники в Казахстан на уборку урожая', 'казахстан'],
  ];
  for (const [text, want] of cases) {
    assert.equal(abroadWork(text).toLowerCase(), want, text);
  }
});

test('заказу и вакансии хватает одного названия места', () => {
  const cases = [
    ['Сварщик\nвахта 30/30\nЯкутск', 'якутск'],
    ['Повар\nАлматы', 'алматы'],
    ['Разнорабочий на склад\n\nМосква', 'москва'],
    ['Сиделка для бабушки, США, Нью-Йорк', 'сша'],
  ];
  for (const [text, want] of cases) {
    assert.equal(abroadWork(text, { job: true }).toLowerCase(), want, text);
  }
});

test('товар оттуда, заведение с «заграничным» именем и валюта — не заграница', () => {
  const ok = [
    'Продаю машину из Кореи, растаможена, тел 0700123456',
    'Одежда из Турции и Китая, режим работы 9-18',
    'Магазин турецкой одежды ищет продавца, зарплата 25000',
    'Грузоперевозки Бишкек — Москва, недорого',
    'Туры в Турцию и Дубай, горящие путёвки',
    'Требуется повар в кафе «Сеул», зарплата 30000',
    'Требуется бариста в кофейню Стамбул, Бишкек',
    'Зарплата от 500 долларов США, программист, Бишкек',
    'Посольство США в Бишкеке приглашает водителя',
    'Корейская кухня ищет официанта, зарплата 20000',
    'Требуется работник на границе с Казахстаном, Кара-Суу',
    'Продаю вещи из-за границы, оригинал',
    'Вакансии на сайте шабашка.рф',
    'Требуется продавец на Московскую, зарплата 20000',
    'Нужен сантехник срочно ор чуй 8й мкр 2000с',
  ];
  for (const text of ok) assert.equal(abroadWork(text), '', text);
});

test('то же самое и для заказа с вакансией — иначе без работы остались бы свои', () => {
  const ok = [
    'Повар в корейский ресторан, Бишкек',
    'Требуется продавец в магазин одежды из Турции и Китая, Ош',
    'Программист, зарплата 1000 долларов США, Бишкек',
    'Уборщица в офис, Бишкек, Аламедин-1',
  ];
  for (const text of ok) assert.equal(abroadWork(text, { job: true }), '', text);
});

test('пустое и мусорное на вход не роняет проверку', () => {
  for (const value of [undefined, null, '', 0, {}, []]) {
    assert.equal(abroadWork(value), '');
  }
});
